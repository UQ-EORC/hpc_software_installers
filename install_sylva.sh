#!/usr/bin/env bash
#
# install_sylva.sh - install Sylva (https://github.com/UQ-EORC/Sylva) into its
# own Python environment on this cluster (RHEL 9 / Lmod).
#
# Usage:
#   ./install_sylva.sh [options] <install_prefix>
#
# Options:
#   -v VERSION   sylva-rs release from PyPI, e.g. 1.1.0 (default: latest)
#   -g REF       build from GitHub branch/tag REF instead of PyPI (compiles the
#                Rust core; installs a private Rust toolchain under the prefix)
#   -n           don't add SYLVA_HOME / PATH settings to ~/.bashrc
#   -h           show this help
#
# After install (and a new shell, or 'source ~/.bashrc'):
#   sylva --help                       # the command-line tool
#   source $SYLVA_HOME/activate.sh     # Python environment with 'import sylva'
#
set -euo pipefail

SYLVA_VERSION=""
GIT_REF=""
UPDATE_BASHRC=1
JOBS="$(nproc)"
REPO_URL="https://github.com/UQ-EORC/Sylva.git"

RUNTIME_MODULES=(
    python/3.12.3-gcccore-13.3.0
)

usage() { sed -n '3,19p' "$0" | sed 's/^# \{0,1\}//'; exit "${1:-0}"; }
log()   { printf '\n\033[1;34m==> %s\033[0m\n' "$*"; }
die()   { printf '\033[1;31mERROR: %s\033[0m\n' "$*" >&2; exit 1; }

while getopts "v:g:nh" opt; do
    case "$opt" in
        v) SYLVA_VERSION="$OPTARG" ;;
        g) GIT_REF="$OPTARG" ;;
        n) UPDATE_BASHRC=0 ;;
        h) usage 0 ;;
        *) usage 1 ;;
    esac
done
shift $((OPTIND - 1))
[[ $# -eq 1 ]] || usage 1
[[ -z "$SYLVA_VERSION" || -z "$GIT_REF" ]] || die "-v and -g can't be used together"

mkdir -p "$1" || die "cannot create install prefix '$1'"
PREFIX="$(cd "$1" && pwd)"
[[ -w "$PREFIX" ]] || die "install prefix '$PREFIX' is not writable"
VENV="$PREFIX/venv"

# ---------------------------------------------------------------------------
# Environment
# ---------------------------------------------------------------------------
# VirtualGL's LD_PRELOAD fakers spam errors in every child process; not needed to install.
unset LD_PRELOAD

if ! type module &>/dev/null; then
    # shellcheck disable=SC1091
    source /etc/profile.d/modules.sh 2>/dev/null || die "Lmod 'module' command not available"
fi

log "Loading modules"
module purge &>/dev/null || true
for m in "${RUNTIME_MODULES[@]}"; do
    module load "$m" || die "failed to load module $m"
done

# ---------------------------------------------------------------------------
# Python environment + Sylva
# ---------------------------------------------------------------------------
if [[ ! -x "$VENV/bin/python" ]]; then
    log "Creating Python environment in $VENV"
    python3 -m venv "$VENV"
fi
"$VENV/bin/pip" install -q --upgrade pip

if [[ -n "$GIT_REF" ]]; then
    # The cluster's Rust modules are older than Sylva's dependencies need, so
    # use a private rustup toolchain kept under the prefix.
    export RUSTUP_HOME="$PREFIX/rust/rustup" CARGO_HOME="$PREFIX/rust/cargo"
    export PATH="$CARGO_HOME/bin:$PATH"
    if [[ ! -x "$CARGO_HOME/bin/cargo" ]]; then
        log "Installing Rust toolchain into $PREFIX/rust"
        curl -sSf https://sh.rustup.rs | sh -s -- -y -q --no-modify-path --profile minimal \
            --default-toolchain stable
    else
        log "Updating Rust toolchain"
        rustup update -q stable
    fi

    log "Building Sylva from GitHub ($GIT_REF)"
    CHECKOUT="$PREFIX/src/Sylva"
    if [[ -d "$CHECKOUT/.git" ]]; then
        git -C "$CHECKOUT" fetch -q origin
        git -C "$CHECKOUT" checkout -q "$GIT_REF"
        git -C "$CHECKOUT" pull -q --ff-only 2>/dev/null || true   # no-op for a tag
    else
        mkdir -p "$PREFIX/src"
        git clone -q --branch "$GIT_REF" "$REPO_URL" "$CHECKOUT"
    fi
    CARGO_BUILD_JOBS="$JOBS" "$VENV/bin/pip" install --upgrade "$CHECKOUT"
else
    log "Installing sylva-rs ${SYLVA_VERSION:-(latest)} from PyPI"
    "$VENV/bin/pip" install -q --upgrade "sylva-rs${SYLVA_VERSION:+==$SYLVA_VERSION}"
fi
INSTALLED_VERSION="$("$VENV/bin/python" -c 'from importlib.metadata import version; print(version("sylva-rs"))')"

# ---------------------------------------------------------------------------
# Launcher ('sylva' command) and activate.sh (Python environment)
# ---------------------------------------------------------------------------
mkdir -p "$PREFIX/bin"
{
    cat <<EOF
#!/usr/bin/env bash
# Sylva launcher generated by install_sylva.sh
SYLVA_BIN="$VENV/bin/sylva"
SYLVA_MODULES="${RUNTIME_MODULES[*]}"
EOF
    cat <<'EOF'

die() { echo "sylva: $*" >&2; exit 1; }

if ! type module &>/dev/null; then
    source /etc/profile.d/modules.sh 2>/dev/null || die "Lmod 'module' command not available"
fi
# shellcheck disable=SC2086
module load $SYLVA_MODULES &>/dev/null || die "failed to load modules: $SYLVA_MODULES"
exec "$SYLVA_BIN" "$@"
EOF
} > "$PREFIX/bin/sylva"
chmod +x "$PREFIX/bin/sylva"

cat > "$PREFIX/activate.sh" <<EOF
# Source this file for a Python environment with Sylva: source $PREFIX/activate.sh
# ('deactivate' leaves it again)
if ! type module &>/dev/null; then
    source /etc/profile.d/modules.sh 2>/dev/null
fi
module load ${RUNTIME_MODULES[*]}
source "$VENV/bin/activate"
EOF

# ---------------------------------------------------------------------------
# Environment: SYLVA_HOME + PATH
# ---------------------------------------------------------------------------
cat > "$PREFIX/sylva_env.sh" <<EOF
# Source this file to use Sylva: source $PREFIX/sylva_env.sh
export SYLVA_HOME="$PREFIX"
case ":\$PATH:" in
    *":\$SYLVA_HOME/bin:"*) ;;
    *) export PATH="\$SYLVA_HOME/bin:\$PATH" ;;
esac
EOF

if [[ $UPDATE_BASHRC -eq 1 ]]; then
    log "Adding SYLVA_HOME to ~/.bashrc"
    BASHRC="$HOME/.bashrc"
    touch "$BASHRC"
    # Replace any block from a previous install so re-running doesn't duplicate it
    sed -i '/^# >>> sylva >>>$/,/^# <<< sylva <<<$/d' "$BASHRC"
    cat >> "$BASHRC" <<EOF
# >>> sylva >>>
# Added by install_sylva.sh
[ -f "$PREFIX/sylva_env.sh" ] && source "$PREFIX/sylva_env.sh"
# <<< sylva <<<
EOF
fi

log "Done"
cat <<EOF
Sylva (sylva-rs $INSTALLED_VERSION) installed to: $PREFIX

EOF
if [[ $UPDATE_BASHRC -eq 1 ]]; then
    echo "SYLVA_HOME and PATH were added to ~/.bashrc. Open a new shell, or run:"
else
    echo "To set SYLVA_HOME and PATH, run (or add to your ~/.bashrc):"
fi
cat <<EOF
    source $PREFIX/sylva_env.sh

Then:
    sylva --help                           # command-line tool
    source \$SYLVA_HOME/activate.sh         # Python environment with 'import sylva'

Reading RIEGL .rxp / .rdbx files needs RiVLib / the RDB SDK: set RIVLIB_PATH /
RDBLIB_PATH to where you extracted them (see https://uq-eorc.github.io/Sylva/install/).
EOF
