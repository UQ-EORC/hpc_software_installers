#!/usr/bin/env bash
#
# install_libreoffice_calc.sh - install LibreOffice Calc on this cluster
# (RHEL 9) from the official LibreOffice RPMs, without root.
#
# Usage:
#   ./install_libreoffice_calc.sh [options] <install_prefix>
#
# Options:
#   -v VERSION   LibreOffice release, e.g. 26.8.3   (default: newest stable)
#   -n           don't add LIBREOFFICE_HOME / PATH settings to ~/.bashrc, or
#                a Calc icon to your desktop and applications menu
#   -h           show this help
#
# After install (and a new shell, or 'source ~/.bashrc'), run:
#   localc [file ...]           # Calc
#   localc --headless --convert-to xlsx data.csv   # convert, no display needed
#
set -euo pipefail

LO_VERSION=""
UPDATE_BASHRC=1
WORKBASE="${TMPDIR:-/tmp}"
BASE_URL="https://download.documentfoundation.org/libreoffice/stable"

# The RPMs Calc needs: the core, Calc, English UI and spelling, icons, fonts,
# import/export filters, GTK integration and Python macros. Writer, Impress,
# Draw, Base and Math are left out.
# Names are prefixed with libreoffice<series>- or libobasis<series>-, e.g.
# libreoffice26.8-calc-26.8.3.1-1.x86_64.rpm.
PACKAGES=(
    'libreoffice:[0-9]' 'libreoffice:ure-' 'libreoffice:calc-'
    'libreoffice:en-US-' 'libreoffice:dict-en-' 'libreoffice:freedesktop-menus-'
    'libobasis:core-' 'libobasis:calc-' 'libobasis:en-US-'
    'libobasis:images-' 'libobasis:ooofonts-' 'libobasis:ooolinguistic-'
    'libobasis:graphicfilter-' 'libobasis:xsltfilter-'
    'libobasis:gnome-integration-' 'libobasis:pyuno-'
    'libobasis:python-script-provider-'
)

usage() { sed -n '3,18p' "$0" | sed 's/^# \{0,1\}//'; exit "${1:-0}"; }
log()   { printf '\n\033[1;34m==> %s\033[0m\n' "$*"; }
die()   { printf '\033[1;31mERROR: %s\033[0m\n' "$*" >&2; exit 1; }

while getopts "v:nh" opt; do
    case "$opt" in
        v) LO_VERSION="$OPTARG" ;;
        n) UPDATE_BASHRC=0 ;;
        h) usage 0 ;;
        *) usage 1 ;;
    esac
done
shift $((OPTIND - 1))
[[ $# -eq 1 ]] || usage 1

command -v rpm2cpio &>/dev/null && command -v cpio &>/dev/null \
    || die "rpm2cpio and cpio are needed to unpack the RPMs"

mkdir -p "$1" || die "cannot create install prefix '$1'"
PREFIX="$(cd "$1" && pwd)"
[[ -w "$PREFIX" ]] || die "install prefix '$PREFIX' is not writable"

if [[ -z "$LO_VERSION" ]]; then
    log "Finding the newest LibreOffice release"
    LO_VERSION="$(curl -fsSL "$BASE_URL/" | grep -oE 'href="[0-9]+(\.[0-9]+)+/"' \
        | grep -oE '[0-9]+(\.[0-9]+)+' | sort -V | tail -1)" || true
    [[ -n "$LO_VERSION" ]] || die "could not read the release list at $BASE_URL"
fi

WORKDIR="$(mktemp -d "${WORKBASE%/}/libreoffice-${USER}-XXXXXX")"
trap 'rm -rf "$WORKDIR"' EXIT
echo "Install prefix : $PREFIX"
echo "Version        : $LO_VERSION"

# ---------------------------------------------------------------------------
# Download and unpack
# ---------------------------------------------------------------------------
TARBALL="LibreOffice_${LO_VERSION}_Linux_x86-64_rpm.tar.gz"
log "Downloading $TARBALL"
curl -fsSL --retry 3 -o "$WORKDIR/$TARBALL" "$BASE_URL/$LO_VERSION/rpm/x86_64/$TARBALL" \
    || die "download failed - is $LO_VERSION a current release? See $BASE_URL/"
tar xzf "$WORKDIR/$TARBALL" -C "$WORKDIR"
RPMS="$(echo "$WORKDIR"/LibreOffice_*/RPMS)"
[[ -d "$RPMS" ]] || die "unexpected tarball layout: no RPMS directory"

log "Unpacking Calc"
SERIES="${LO_VERSION%.*}"   # 26.8.3 -> 26.8
mkdir -p "$WORKDIR/root"
for pkg in "${PACKAGES[@]}"; do
    pat="${pkg%%:*}${SERIES}-${pkg#*:}*"
    found=0
    for rpm in "$RPMS"/$pat.rpm; do
        [[ -e "$rpm" ]] || continue
        found=1
        (cd "$WORKDIR/root" && rpm2cpio "$rpm" | cpio -idm --quiet)
    done
    [[ $found -eq 1 ]] || die "no package matching $pat in $TARBALL"
done
LO_DIR="$(echo "$WORKDIR"/root/opt/libreoffice*)"
[[ -x "$LO_DIR/program/soffice" ]] || die "soffice missing after unpacking"

log "Installing to $PREFIX"
# Replace any previous install so files from an older version don't linger.
rm -rf "$PREFIX/libreoffice"
mv "$LO_DIR" "$PREFIX/libreoffice"
mkdir -p "$PREFIX/share/icons" "$PREFIX/bin"
CALC_ICON="$(echo "$WORKDIR"/root/usr/share/icons/hicolor/256x256/apps/libreoffice*-calc.png)"
cp "$CALC_ICON" "$PREFIX/share/icons/libreoffice-calc.png"

# ---------------------------------------------------------------------------
# Launcher: 'localc' starts Calc, or converts files with --headless
# ---------------------------------------------------------------------------
cat > "$PREFIX/bin/localc" <<EOF
#!/usr/bin/env bash
# LibreOffice Calc launcher generated by install_libreoffice_calc.sh ($LO_VERSION)
#
#   localc [file ...]                               Calc
#   localc --headless --convert-to xlsx data.csv    convert, no display needed
SOFFICE="$PREFIX/libreoffice/program/soffice"
EOF
cat >> "$PREFIX/bin/localc" <<'EOF'

if [[ -z "${DISPLAY:-}" && " $* " != *" --headless "* ]]; then
    echo "localc: no DISPLAY - start a desktop session (e.g. Open OnDemand), or use --headless to convert files" >&2
    exit 1
fi
exec "$SOFFICE" --calc "$@"
EOF
chmod +x "$PREFIX/bin/localc"

# ---------------------------------------------------------------------------
# Environment: LIBREOFFICE_HOME + PATH
# ---------------------------------------------------------------------------
cat > "$PREFIX/libreoffice_env.sh" <<EOF
# Source this file to use LibreOffice Calc: source $PREFIX/libreoffice_env.sh
export LIBREOFFICE_HOME="$PREFIX"
case ":\$PATH:" in
    *":\$LIBREOFFICE_HOME/bin:"*) ;;
    *) export PATH="\$LIBREOFFICE_HOME/bin:\$PATH" ;;
esac
EOF

if [[ $UPDATE_BASHRC -eq 1 ]]; then
    log "Adding LIBREOFFICE_HOME to ~/.bashrc"
    BASHRC="$HOME/.bashrc"
    touch "$BASHRC"
    # Replace any block from a previous install so re-running doesn't duplicate it
    sed -i '/^# >>> libreoffice >>>$/,/^# <<< libreoffice <<<$/d' "$BASHRC"
    cat >> "$BASHRC" <<EOF
# >>> libreoffice >>>
# Added by install_libreoffice_calc.sh
[ -f "$PREFIX/libreoffice_env.sh" ] && source "$PREFIX/libreoffice_env.sh"
# <<< libreoffice <<<
EOF
fi

# ---------------------------------------------------------------------------
# Desktop icon and applications-menu entry. Programs started from the desktop
# don't read ~/.bashrc, so they point at the launcher by full path.
# ---------------------------------------------------------------------------
DESKTOP_FILE="$PREFIX/share/applications/libreoffice-calc.desktop"
mkdir -p "$(dirname "$DESKTOP_FILE")"
cat > "$DESKTOP_FILE" <<EOF
[Desktop Entry]
Version=1.0
Type=Application
Name=LibreOffice Calc
GenericName=Spreadsheet
Comment=Create and edit spreadsheets
Exec="$PREFIX/bin/localc" %U
Icon=$PREFIX/share/icons/libreoffice-calc.png
Terminal=false
Categories=Office;Spreadsheet;
MimeType=text/csv;text/tab-separated-values;application/vnd.oasis.opendocument.spreadsheet;application/vnd.openxmlformats-officedocument.spreadsheetml.sheet;application/vnd.ms-excel;
StartupWMClass=libreoffice-calc
EOF

if [[ $UPDATE_BASHRC -eq 1 ]]; then
    log "Adding Calc to the desktop and applications menu"
    # The desktop folder is set per user (on Bunya's desktops it's the home directory).
    DESKTOP_DIR="$(xdg-user-dir DESKTOP 2>/dev/null || echo "$HOME/Desktop")"
    for dir in "$HOME/.local/share/applications" "$DESKTOP_DIR"; do
        mkdir -p "$dir"
        install -m 755 "$DESKTOP_FILE" "$dir/libreoffice-calc.desktop"
        # Desktops other than MATE also want the icon marked as trusted.
        gio set "$dir/libreoffice-calc.desktop" metadata::trusted true &>/dev/null || true
    done
fi

log "Done"
cat <<EOF
LibreOffice Calc $LO_VERSION installed to: $PREFIX

EOF
if [[ $UPDATE_BASHRC -eq 1 ]]; then
    echo "Calc was added to your desktop and applications menu."
    echo "LIBREOFFICE_HOME and PATH were added to ~/.bashrc. Open a new shell, or run:"
else
    echo "To set LIBREOFFICE_HOME and PATH, run (or add to your ~/.bashrc):"
fi
cat <<EOF
    source $PREFIX/libreoffice_env.sh

Then run Calc with:
    localc                                          # GUI
    localc --headless --convert-to xlsx data.csv    # convert, no display needed
EOF
if [[ $UPDATE_BASHRC -eq 0 ]]; then
    cat <<EOF

To add a Calc icon to your desktop and applications menu, run:
    install -m 755 $DESKTOP_FILE "\$(xdg-user-dir DESKTOP)"
    install -m 755 $DESKTOP_FILE ~/.local/share/applications/
EOF
fi
