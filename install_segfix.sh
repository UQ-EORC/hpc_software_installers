#!/usr/bin/env bash
#
# install_segfix.sh - install Segfix (https://github.com/UQ-EORC/Segfix) into
# its own Python environment on this cluster (RHEL 9 / Lmod).
#
# Usage:
#   ./install_segfix.sh [options] <install_prefix>
#
# Options:
#   -v VERSION   Segfix release from PyPI, e.g. 1.3.0   (default: latest)
#   -g REF       install from a GitHub checkout of branch/tag REF instead of
#                PyPI (editable, so Segfix's updater uses 'git pull')
#   -n           don't add SEGFIX_HOME / PATH settings to ~/.bashrc
#   -h           show this help
#
# After install (and a new shell, or 'source ~/.bashrc'), run:
#   segfix                      # GUI, uses VirtualGL when available
#
set -euo pipefail

SEGFIX_VERSION=""
GIT_REF=""
UPDATE_BASHRC=1
REPO_URL="https://github.com/UQ-EORC/Segfix.git"

# Segfix needs Python 3.10-3.12; PyQt6 comes from its wheel, so nothing else is needed.
RUNTIME_MODULES=(
    python/3.12.3-gcccore-13.3.0
)

usage() { sed -n '3,18p' "$0" | sed 's/^# \{0,1\}//'; exit "${1:-0}"; }
log()   { printf '\n\033[1;34m==> %s\033[0m\n' "$*"; }
die()   { printf '\033[1;31mERROR: %s\033[0m\n' "$*" >&2; exit 1; }

while getopts "v:g:nh" opt; do
    case "$opt" in
        v) SEGFIX_VERSION="$OPTARG" ;;
        g) GIT_REF="$OPTARG" ;;
        n) UPDATE_BASHRC=0 ;;
        h) usage 0 ;;
        *) usage 1 ;;
    esac
done
shift $((OPTIND - 1))
[[ $# -eq 1 ]] || usage 1
[[ -z "$SEGFIX_VERSION" || -z "$GIT_REF" ]] || die "-v and -g can't be used together"

mkdir -p "$1" || die "cannot create install prefix '$1'"
PREFIX="$(cd "$1" && pwd)"
[[ -w "$PREFIX" ]] || die "install prefix '$PREFIX' is not writable"
VENV="$PREFIX/venv"

# ---------------------------------------------------------------------------
# Environment
# ---------------------------------------------------------------------------
# VirtualGL's LD_PRELOAD fakers spam errors in every child process; not needed to install.
unset LD_PRELOAD

if ! type module &>/dev/null; then
    # shellcheck disable=SC1091
    source /etc/profile.d/modules.sh 2>/dev/null || die "Lmod 'module' command not available"
fi

log "Loading modules"
module purge &>/dev/null || true
for m in "${RUNTIME_MODULES[@]}"; do
    module load "$m" || die "failed to load module $m"
done

# ---------------------------------------------------------------------------
# Python environment + Segfix
# ---------------------------------------------------------------------------
if [[ ! -x "$VENV/bin/python" ]]; then
    log "Creating Python environment in $VENV"
    python3 -m venv "$VENV"
fi
"$VENV/bin/pip" install -q --upgrade pip

if [[ -n "$GIT_REF" ]]; then
    log "Installing Segfix from GitHub ($GIT_REF)"
    CHECKOUT="$PREFIX/src/Segfix"
    if [[ -d "$CHECKOUT/.git" ]]; then
        git -C "$CHECKOUT" fetch -q origin
        git -C "$CHECKOUT" checkout -q "$GIT_REF"
        git -C "$CHECKOUT" pull -q --ff-only 2>/dev/null || true   # no-op for a tag
    else
        mkdir -p "$PREFIX/src"
        git clone -q --branch "$GIT_REF" "$REPO_URL" "$CHECKOUT"
    fi
    "$VENV/bin/pip" install -q -e "$CHECKOUT"
else
    log "Installing Segfix ${SEGFIX_VERSION:-(latest)} from PyPI"
    "$VENV/bin/pip" install -q --upgrade "segfix${SEGFIX_VERSION:+==$SEGFIX_VERSION}"
fi
INSTALLED_VERSION="$("$VENV/bin/python" -c 'from importlib.metadata import version; print(version("segfix"))')"

# ---------------------------------------------------------------------------
# Launcher: 'segfix' command that loads the Python module and starts the GUI
# through VirtualGL when available
# ---------------------------------------------------------------------------
mkdir -p "$PREFIX/bin"
{
    cat <<EOF
#!/usr/bin/env bash
# Segfix launcher generated by install_segfix.sh
SEGFIX_BIN="$VENV/bin/segfix"
SEGFIX_MODULES="${RUNTIME_MODULES[*]}"
EOF
    cat <<'EOF'

die() { echo "segfix: $*" >&2; exit 1; }

if ! type module &>/dev/null; then
    source /etc/profile.d/modules.sh 2>/dev/null || die "Lmod 'module' command not available"
fi
# shellcheck disable=SC2086
module load $SEGFIX_MODULES &>/dev/null || die "failed to load modules: $SEGFIX_MODULES"

[[ -n "${DISPLAY:-}" ]] || die "no DISPLAY - start a desktop session (e.g. Open OnDemand) first"

# Use VirtualGL for GPU rendering unless the session already preloads it.
if [[ "${LD_PRELOAD:-}" != *vglfaker* ]]; then
    command -v vglrun &>/dev/null || module load virtualgl &>/dev/null || true
    command -v vglrun &>/dev/null && exec vglrun "$SEGFIX_BIN" "$@"
fi
exec "$SEGFIX_BIN" "$@"
EOF
} > "$PREFIX/bin/segfix"
chmod +x "$PREFIX/bin/segfix"

# ---------------------------------------------------------------------------
# Environment: SEGFIX_HOME + PATH
# ---------------------------------------------------------------------------
cat > "$PREFIX/segfix_env.sh" <<EOF
# Source this file to use Segfix: source $PREFIX/segfix_env.sh
export SEGFIX_HOME="$PREFIX"
case ":\$PATH:" in
    *":\$SEGFIX_HOME/bin:"*) ;;
    *) export PATH="\$SEGFIX_HOME/bin:\$PATH" ;;
esac
EOF

if [[ $UPDATE_BASHRC -eq 1 ]]; then
    log "Adding SEGFIX_HOME to ~/.bashrc"
    BASHRC="$HOME/.bashrc"
    touch "$BASHRC"
    # Replace any block from a previous install so re-running doesn't duplicate it
    sed -i '/^# >>> segfix >>>$/,/^# <<< segfix <<<$/d' "$BASHRC"
    cat >> "$BASHRC" <<EOF
# >>> segfix >>>
# Added by install_segfix.sh
[ -f "$PREFIX/segfix_env.sh" ] && source "$PREFIX/segfix_env.sh"
# <<< segfix <<<
EOF
fi

log "Done"
cat <<EOF
Segfix $INSTALLED_VERSION installed to: $PREFIX

EOF
if [[ $UPDATE_BASHRC -eq 1 ]]; then
    echo "SEGFIX_HOME and PATH were added to ~/.bashrc. Open a new shell, or run:"
else
    echo "To set SEGFIX_HOME and PATH, run (or add to your ~/.bashrc):"
fi
cat <<EOF
    source $PREFIX/segfix_env.sh

Then run Segfix with:
    segfix                                 # GUI (uses VirtualGL when available)
EOF
